// PDF page-cache isolation and cancellation; mocked rendering/inference.
const assert = require('node:assert/strict');
const { boot, flush, fields, reply } = require('./test_persistence_frontend.cjs');
const converted = call => call.resolve({ ok: true, headers: { get: name => name === 'X-Page-Count' ? '2' : '0' }, blob: async () => new Blob(['JPEG'], { type: 'image/jpeg' }) });
(async () => {
  const page = boot(); await flush();
  page.el('#image-input').files = [new File(['PDF'], 'packet.pdf', { type: 'application/pdf' })];
  page.el('#image-input').listeners.change();
  page.el('#language-continue').listeners.click();
  converted(page.calls[0]); await flush();
  reply(page.calls[1], { fields }); await flush();
  assert.equal(page.el('#page-control').hidden, false);
  page.el('#page-select').value = '1'; page.el('#page-select').listeners.change();
  assert.equal(page.calls[2].url, '/api/convert');
  assert.equal(page.calls[2].options.body.get('page'), '1');
  converted(page.calls[2]); await flush();
  reply(page.calls[3], { fields: [{ ...fields[0], label: 'Second page' }] }); await flush();
  page.el('#page-select').value = '0'; page.el('#page-select').listeners.change(); await flush();
  assert.equal(page.calls.length, 4, 'Cached first page needs neither conversion nor inference');
  assert.match(page.el('#ask-label').textContent, /Fictional name/);
  page.el('#page-select').value = '1'; page.el('#page-select').listeners.change(); await flush();
  assert.equal(page.calls.length, 4);
  assert.match(page.el('#ask-label').textContent, /Second page/);
  page.el('#reset-button').listeners.click(); await flush();
  assert.equal(page.el('#page-control').hidden, true);
  const pending = boot(); await flush();
  pending.el('#image-input').files = [new File(['PDF'], 'pending.pdf', { type: 'application/pdf' })];
  pending.el('#image-input').listeners.change(); pending.el('#language-continue').listeners.click(); converted(pending.calls[0]); await flush();
  reply(pending.calls[1], { fields }); await flush();
  pending.el('#page-select').value = '1'; pending.el('#page-select').listeners.change();
  pending.el('#reset-button').listeners.click();
  converted(pending.calls[2]); await flush();
  assert.equal(pending.calls.length, 3, 'Reset discards late PDF conversion before inference');
  assert.equal(pending.el('#result-state').hidden, true);
  const failed = boot(); await flush();
  failed.el('#image-input').files = [new File(['PDF'], 'error.pdf', { type: 'application/pdf' })];
  failed.el('#image-input').listeners.change(); failed.el('#language-continue').listeners.click(); converted(failed.calls[0]); await flush();
  reply(failed.calls[1], { fields }); await flush();
  failed.el('#page-select').value = '1'; failed.el('#page-select').listeners.change();
  failed.calls[2].resolve({ ok: false, json: async () => ({ error: 'This PDF page could not be converted.' }) }); await flush();
  assert.match(failed.el('#error').textContent, /could not be converted/);
  failed.el('#page-select').value = '0'; failed.el('#page-select').listeners.change(); await flush();
  assert.equal(failed.calls.length, 3, 'A page conversion error preserves prior successful cache');
  assert.equal(failed.el('#result-state').hidden, false);
  console.log('PASS: PDF page selection, separate page caches, cached page round trip, reset, late conversion guard, error cache preservation');
})().catch(err => { console.error(err); process.exitCode = 1; });
